"""Bake the two fixed watermark captions into an antialiased coverage atlas.

Requires Pillow and an explicitly supplied bold TrueType font. Only rasterized
lettering is emitted; no font program or user filesystem path is distributed.
Example: python Scripts/generate_watermark_text.py --font <Arial Bold.ttf>
"""
import argparse
from pathlib import Path
import struct
from PIL import Image, ImageDraw, ImageFont

parser = argparse.ArgumentParser(description=__doc__)
parser.add_argument('--font', type=Path, required=True)
args = parser.parse_args()
width, height = 448, 80
font = ImageFont.truetype(str(args.font), 80)  # 2x the design-space text size.
atlas = Image.new('L', (width, height * 2))
draw = ImageDraw.Draw(atlas)
for index, caption in enumerate(('DLSS 5 Off', 'DLSS 5 On')):
    left, top, right, bottom = draw.textbbox((0, 0), caption, font=font)
    assert right-left < width and bottom-top < height
    draw.text(((width-right-left)/2, index*height+(height-bottom-top)/2), caption, font=font, fill=255)
words = struct.unpack('<' + 'I'*(len(atlas.tobytes())//4), atlas.tobytes())
lines = ['// Generated by Scripts/generate_watermark_text.py. Raster lettering only; no font file.',
         '#pragma once', '', 'namespace DLSS5NRWatermarkText', '{',
         f'    constexpr uint32 Width = {width};', f'    constexpr uint32 Height = {height};',
         '    // OFF then ON, four coverage bytes per uint32, least-significant byte first.',
         '    static const uint32 Pixels[] = {']
lines += ['        '+','.join(f'0x{v:08x}u' for v in words[i:i+8])+',' for i in range(0,len(words),8)]
lines += ['    };', '}', '']
target = Path(__file__).resolve().parents[1] / 'Plugins/DLSS5ForUE5/Source/DLSS5ForUE5_nvngx/Private/DLSS5NRWatermarkText.h'
target.write_text('\n'.join(lines),encoding='utf-8')
print(f'Generated {width}x{height*2} coverage atlas ({len(words)*4} bytes).')
